/* ---------- quiz 2: Food Cost Maths ---------- */

function foodCostScenario() {
  const milkRate = pick([0.042, 0.048, 0.052, 0.06]);
  const milkMl = pick(steps(40, 60, 5));
  const waterRate = pick([0.00125, 0.00175, 0.002]);
  const waterMl = pick(steps(40, 60, 5));
  const teaRate = pick([0.25, 0.3, 0.35, 0.4]);
  const teaG = pick([2, 3, 4]);
  const gingerRate = pick([0.12, 0.15, 0.18, 0.2]);
  const gingerG = pick([2, 3, 4, 5]);
  const sugarRate = pick([0.03, 0.04, 0.05]);
  const sugarG = pick([5, 6, 8]);

  const milk = round(milkMl * milkRate, 4);
  const water = round(waterMl * waterRate, 4);
  const tea = round(teaG * teaRate, 4);
  const ginger = round(gingerG * gingerRate, 4);
  const sugar = round(sugarG * sugarRate, 4);

  // the chain that runs Q13 -> Q17, exactly as the original does
  const main = round(milk + water, 4);          // "main ingredients"
  const extras = round(ginger + sugar, 4);      // "extra ingredients"
  const total = round(main + extras, 4);
  const wastePct = pick([4, 5, 6]);
  const wasteAmt = round((total * wastePct) / 100, 2);
  const foodCost = round(total + wasteAmt, 4);

  const targetA = pick([25, 30, 33]);
  const targetB = pick([35, 40, 45]);

  // Stock and monitoring — built backwards from the food-cost % so that the whole
  // chain (Q21 consumed -> Q22 actual % -> Q24 points over target) stays exact and
  // the shop is always over target, never under.
  const dailyRev = pick([8000, 10000, 12000, 15000]);
  const weekSales = dailyRev * 7;
  const actualPct = round(targetA + pick([3, 4.5, 5, 6.5, 8, 10.5]), 1);
  const consumed = round((weekSales * actualPct) / 100, 0);
  const opening = Math.round((consumed * pick([0.3, 0.4, 0.5])) / 1000) * 1000;
  const closing = Math.round((consumed * pick([0.2, 0.25, 0.3])) / 1000) * 1000;
  const purchases = consumed - opening + closing;

  // percentages that come out clean
  const revenue = pick([300000, 400000, 500000, 600000]);
  const ebitdaPct = pick([15, 20, 25, 30, 33]);
  const rentPct = pick([8, 10, 12, 15]);

  return {
    milkRate, milkMl, milk,
    waterRate, waterMl, water,
    teaRate, teaG, tea,
    gingerRate, gingerG, ginger,
    sugarRate, sugarG, sugar,
    threeSum: round(milk + water + tea, 4),
    twoSum: round(ginger + sugar, 4),
    main, extras, total, wastePct, wasteAmt, foodCost,
    targetA, targetB,
    pctOfBase: pick([200, 300, 400, 500]),
    pctOf: pick([10, 15, 20, 25]),
    asDecimal: pick([20, 30, 40, 60, 75]),
    marginBase: pick([25, 30, 33, 35, 40]),
    butterPerKg: pick([400, 450, 500]),
    butterKg: pick([0.01, 0.015, 0.02]),
    onionPerKg: pick([30, 40, 50]),
    onionKg: pick([0.02, 0.025, 0.03]),
    opening, purchases, closing, consumed,
    dailyRev, weekSales, actualPct,
    revenue, ebitdaPct, rentPct,
    snackCost: pick([3, 4, 5, 6]),
    snackTarget: pick([20, 25, 40, 50])
  };
}

