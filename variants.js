/* Number shuffling.

   Each quiz has a scenario generator that picks a fresh, self-consistent set of
   numbers, and a recipe per question that rebuilds the wording, the answer and the
   working from that scenario. All plain arithmetic — nothing is fetched, nothing is
   generated by AI. Questions with no recipe simply keep their original numbers.

   A recipe is { text, answer, working, hint?, formula?, options?, tolerance? },
   each either a value or a function of the scenario. Anything it does not set
   (unit, suffix, tag, type) is inherited from the original question. */

/* ---------- helpers ---------- */

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

// step through a range, e.g. steps(10, 60, 5) -> [10, 15, ... 60]
function steps(min, max, step) {
  const out = [];
  for (let v = min; v <= max + 1e-9; v += step) out.push(Math.round(v * 1e6) / 1e6);
  return out;
}

const round = (v, dp = 2) => Math.round(v * 10 ** dp) / 10 ** dp;

// 1,20,000 / 3.3875 — trims trailing zeros, max 4 decimals
function num(v) {
  const r = Math.round(v * 10000) / 10000;
  const neg = r < 0;
  const [w, f] = String(Math.abs(r)).split(".");
  const grouped = w.length <= 3
    ? w
    : w.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ",") + "," + w.slice(-3);
  return (neg ? "-" : "") + grouped + (f ? `.${f}` : "");
}

const rs = (v) => `₹${num(v)}`; // rupees

