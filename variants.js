function businessScenario() {
  const teaPrice = pick([15, 20, 25, 30]);
  const teaCost = pick([5, 6, 7, 8]);
  const teaPriceB = pick([12, 15, 18, 20]);

  // sandwich: cost is a clean percentage of price, so Q14 stays a tidy number
  const sandPrice = pick([60, 80, 100, 120]);
  const sandPct = pick([25, 30, 35, 40]);
  const sandCost = (sandPrice * sandPct) / 100;
  const sandQty = pick(steps(30, 70, 10));

  // Q8/Q9: ingredient spend is a clean percentage of tea sales
  const q8Teas = pick([100, 150, 200]);
  const q8Pct = pick([30, 35, 40]);
  const q8Sales = q8Teas * teaPrice;
  const q8Ing = (q8Sales * q8Pct) / 100;

  // Q15: wastage is a clean percentage of stock
  const stock = pick([4000, 5000, 6000, 8000, 10000]);
  const wastePct = pick([4, 5, 6, 8, 10]);
  const wastage = (stock * wastePct) / 100;

  // Q19/21/22: fixed costs
  const rent = pick([24000, 30000, 36000, 45000]);   // all divide by 30
  const staff = pick([2, 3, 4]);
  const salary = pick([12000, 15000, 18000]);
  const utilities = pick([8000, 10000, 12000, 15000]);
  const fixedTotal = rent + staff * salary + utilities;
  const monthSales = pick([200000, 250000, 300000, 400000, 500000]);

  // Q25-27: one day's trading, used by all three.
  // Q24 compares the two margins, so they must not tie — keep the snack clearly ahead.
  let daySnackPrice, daySnackCost, dayTeaPrice, dayTeaCost;
  do {
    daySnackPrice = pick([80, 100, 120]);
    daySnackCost = pick([50, 60, 70]);
    dayTeaPrice = pick([20, 25, 30]);
    dayTeaCost = pick([7, 8, 10]);
  } while (daySnackPrice - daySnackCost < dayTeaPrice - dayTeaCost + 5);
  const dayTeaQty = pick(steps(40, 90, 10));
  const daySnackQty = pick(steps(20, 50, 10));
  const daySales = dayTeaQty * dayTeaPrice + daySnackQty * daySnackPrice;
  const dayIng = dayTeaQty * dayTeaCost + daySnackQty * daySnackCost;

  // Q28: target divides exactly by the average bill
  const avgBill = pick([80, 100, 120, 150, 200]);
  const bills = pick([50, 60, 80, 100, 120]);

  return {
    teaPrice, teaCost, teaPriceB,
    q1Cups: pick(steps(10, 60, 5)),
    q2Count: pick(steps(20, 60, 5)),
    q3Teas: pick([2, 3, 4]),
    snackPrice: pick([40, 50, 60, 70]),
    monday: pick(steps(3000, 6000, 100)),
    tuesday: pick(steps(3000, 6000, 100)),
    target: pick([8000, 10000, 12000, 15000]),
    sold: pick(steps(4000, 7500, 100)),
    q6Cups: pick(steps(50, 120, 10)),
    q8Teas, q8Sales, q8Ing, q8Pct,
    bought: pick([2000, 3000, 4000, 5000]),
    usedPct: pick([60, 70, 75, 80]),
    sandPrice, sandCost, sandPct, sandQty,
    stock, wastePct, wastage,
    opening: pick(steps(1500, 4000, 500)),
    purchases: pick(steps(6000, 12000, 1000)),
    closing: pick(steps(1000, 2500, 500)),
    made: pick(steps(30, 80, 10)),
    spilled: pick([2, 3, 4, 5]),
    portions: pick([80, 100, 120]),
    wasted: pick([4, 5, 6, 8]),
    portionPrice: pick([30, 40, 50, 60]),
    rent, staff, salary, utilities, fixedTotal, monthSales,
    lowPrice: pick([10, 12, 15]),
    dayTeaQty, daySnackQty, dayTeaPrice, dayTeaCost,
    daySnackPrice, daySnackCost, daySales, dayIng,
    avgBill, bills
  };
}

